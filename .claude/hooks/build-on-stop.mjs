#!/usr/bin/env node
// Stop hook: when Claude finishes a turn, run a full Next.js production build
// to catch errors `tsc`/eslint miss (route signatures, server/client boundary,
// etc.). Skips when no source changed since the last successful build, so
// pure-conversation turns don't trigger a build. On failure it exits 2 —
// paired with asyncRewake in settings, that wakes Claude back up with the
// build errors to fix.
import { execSync } from "node:child_process";
import { readdirSync, statSync, readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import path from "node:path";

const repo = process.cwd();
const stampFile = path.join(repo, ".claude", ".last-build-sig");
const SKIP_DIRS = new Set(["node_modules", ".next", ".git", ".claude"]);
// Auto-generated by `next build`/`next dev` — never hand-edited. Including it
// would flip the signature on every build and force one spurious rebuild.
const SKIP_FILES = new Set(["next-env.d.ts"]);

// Build a signature of every source file (path + mtime). tsconfig/package.json
// changes count too, since they affect the build.
function collect(dir, acc) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    if (SKIP_DIRS.has(entry.name)) continue;
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) collect(full, acc);
    else if (SKIP_FILES.has(entry.name)) continue;
    else if (/\.(ts|tsx|mts|cts|js|jsx|css)$/i.test(entry.name)) {
      acc.push(`${full}:${statSync(full).mtimeMs}`);
    }
  }
}

const files = [];
collect(repo, files);
for (const f of ["tsconfig.json", "package.json", "next.config.ts", "next.config.js"]) {
  try {
    files.push(`${f}:${statSync(path.join(repo, f)).mtimeMs}`);
  } catch {
    /* file may not exist */
  }
}
files.sort();
const sig = createHash("sha1").update(files.join("|")).digest("hex");

let prev = "";
try {
  prev = readFileSync(stampFile, "utf8").trim();
} catch {
  /* first run */
}

// Nothing changed since the last successful build — don't rebuild.
if (sig === prev) process.exit(0);

try {
  execSync("npm run build", { stdio: "pipe", maxBuffer: 64 * 1024 * 1024 });
  writeFileSync(stampFile, sig);
  process.exit(0);
} catch (e) {
  const out = `${e.stdout ?? ""}${e.stderr ?? ""}`.trim();
  const tail = out.split("\n").slice(-60).join("\n");
  process.stderr.write(`Production build (npm run build) failed:\n\n${tail}\n`);
  process.exit(2);
}
